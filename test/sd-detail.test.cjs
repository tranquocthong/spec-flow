'use strict';
// SD detail level: lean (default) drops the human-only sections, full keeps them,
// and sd-skeleton resolves the level from flag > existing SD > config > default.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const core = require('../lib/core.cjs');

const SRS = [
  '# Feature: Detail Demo',
  '',
  '## Revision History',
  '| Version | Author | Date | Changes |',
  '| --- | --- | --- | --- |',
  '| 1.0 | PO | 2026-11-01 | first |',
  '',
  '## Glossary',
  '| Term | Meaning |',
  '| --- | --- |',
  '| Hold | Reserved amount |',
  '',
  '## 4. User Stories',
  '### US-1: Hold money',
  '- As a payer,',
  '#### Acceptance Criteria',
  '- a hold is created',
  '#### Edge Cases',
  '- amount is zero',
].join('\n');

const gen = (detail) => core.genSd(core.parseSrs(SRS), { type: 'api', feature: 'demo', detail });
const HUMAN_ONLY = [/^### Revision History$/m, /^## 2\. Background/m, /^### 3\.1 Goals$/m, /^## Appendix: Glossary$/m];
const ALWAYS = [/^## 1\. Overview$/m, /^### 3\.2 Non-Goals$/m, /^### 5\.1 Functional Requirements$/m,
  /^### 5\.2 Non-Functional Requirements$/m, /^## 6\. Architecture Overview$/m, /^## 9\. API Design$/m,
  /^### 12\.2 Domain Error Codes$/m, /^### 13\.2 Test Cases/m];

test('genSd defaults to lean and drops only the human-only sections', () => {
  const { sd, stats } = core.genSd(core.parseSrs(SRS), { type: 'api', feature: 'demo' });
  assert.equal(stats.detail, 'lean');
  assert.match(sd, /Detail: \*\*lean\*\*/);
  for (const re of HUMAN_ONLY) assert.doesNotMatch(sd, re);
  for (const re of ALWAYS) assert.match(sd, re);
  assert.doesNotMatch(sd, /§6\.1 Mermaid/, 'lean asks for no §6.1 diagram');
});

test('genSd full keeps the human-only sections', () => {
  const { sd, stats } = gen('full');
  assert.equal(stats.detail, 'full');
  for (const re of HUMAN_ONLY.concat(ALWAYS)) assert.match(sd, re);
  assert.match(sd, /\| Hold \| Reserved amount \|/);
});

test('lean and full harvest the same engine-read rows', () => {
  const l = gen('lean').stats, f = gen('full').stats;
  for (const k of ['fr', 'nfr', 'errorCodes', 'testCases']) assert.equal(l[k], f[k], k);
  assert.ok(gen('lean').sd.length < gen('full').sd.length);
});

test('lean emits no TODO marker for an omitted section', () => {
  const { sd } = gen('lean');
  for (const line of sd.split('\n').filter((x) => /\*\*TODO:MANUAL-REVIEW\*\*/.test(x))) {
    assert.doesNotMatch(line, /§2\.1 Context|list goals from SRS/, line);
  }
});

test('sdDetailOf reads the preamble marker and returns null without one', () => {
  assert.equal(core.sdDetailOf(gen('full').sd), 'full');
  assert.equal(core.sdDetailOf(gen('lean').sd), 'lean');
  assert.equal(core.sdDetailOf('# SD\n\n> Generated by spec-flow Pass-1 from SRS. Design type: **api**.\n'), null);
});

// --- CLI resolution -------------------------------------------------------
const BIN = path.join(__dirname, '..', 'bin', 'flow-tools.cjs');
function project(cfg) {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'sf-detail-'));
  fs.mkdirSync(path.join(d, '.spec-flow'), { recursive: true });
  if (cfg) fs.writeFileSync(path.join(d, '.spec-flow', 'config.json'), JSON.stringify(cfg));
  fs.writeFileSync(path.join(d, 'srs.md'), SRS);
  return d;
}
function run(d, extra) {
  const out = execFileSync('node', [BIN, 'sd-skeleton', '--srs', 'srs.md', '--feature', 'demo', ...extra],
    { cwd: d, encoding: 'utf8' });
  return JSON.parse(out);
}
const sdPath = (d) => path.join(d, '.spec-flow', 'specs', 'demo', 'SD.md');

test('sd-skeleton: no flag, no config -> lean (default)', () => {
  const d = project(null);
  const r = run(d, []);
  assert.equal(r.data.stats.detail, 'lean');
  assert.equal(r.data.stats.detailFrom, 'default');
});

test('sd-skeleton: config sd.detail full is honoured, --detail lean overrides it', () => {
  const d = project({ sd: { detail: 'full' } });
  assert.equal(run(d, []).data.stats.detail, 'full');
  const r = run(d, ['--force', '--detail', 'lean']);
  assert.equal(r.data.stats.detail, 'lean');
  assert.equal(r.data.stats.detailFrom, 'flag');
});

test('sd-skeleton --full forces full', () => {
  const d = project(null);
  assert.equal(run(d, ['--full']).data.stats.detail, 'full');
});

test('sd-skeleton --force keeps the level of the SD it overwrites', () => {
  const d = project(null);
  run(d, ['--full']);
  const r = run(d, ['--force']);
  assert.equal(r.data.stats.detail, 'full');
  assert.equal(r.data.stats.detailFrom, 'existing-sd');
});

test('sd-skeleton --force on a pre-lean SD (no marker) re-harvests it as full', () => {
  const d = project(null);
  fs.mkdirSync(path.dirname(sdPath(d)), { recursive: true });
  fs.writeFileSync(sdPath(d), '# Solution Design: old\n\n## 2. Background & Problem Statement\n');
  const r = run(d, ['--force']);
  assert.equal(r.data.stats.detail, 'full');
  assert.match(fs.readFileSync(sdPath(d), 'utf8'), /^## 2\. Background/m);
});

test('sd-skeleton rejects an unknown --detail value', () => {
  const d = project(null);
  let out;
  try { out = execFileSync('node', [BIN, 'sd-skeleton', '--srs', 'srs.md', '--detail', 'tiny'], { cwd: d, encoding: 'utf8' }); }
  catch (e) { out = e.stdout; }
  assert.match(out, /INVALID_DETAIL/);
});
